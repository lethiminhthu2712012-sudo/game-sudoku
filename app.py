def sound_uri(filename):
    path = ASSETS / filename
    if not path.exists():
        return None
    try:
        data = base64.b64encode(path.read_bytes()).decode("ascii")
        return f"data:audio/mpeg;base64,{data}"
    except OSError:
        return None

def play_sound(filename, loop=False):
    uri = sound_uri(filename)
    if not uri:
        return
    loop_attr = "loop" if loop else ""
    # A short iframe keeps the audio player hidden. Browsers may block
    # autoplay until the player has interacted with the page.
    components.html(
        f"""
        <audio autoplay {loop_attr} style="display:none">
          <source src="{uri}" type="audio/mpeg">
        </audio>
        """,
        height=0,
    )

def image_data_uri(filename):
    path = ASSETS / filename
    if not path.exists():
        return None
    ext = path.suffix.lower()
    mime = "image/png" if ext == ".png" else "image/jpeg"
    data = base64.b64encode(path.read_bytes()).decode("ascii")
    return f"data:{mime};base64,{data}"

