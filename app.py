# Validate the built-in boards; use known-valid Latin-pattern boards
# for levels 3-5 if a hand-edited board contains an invalid row.
def make_valid_solution(seed):
    base = [[(r * 3 + r // 3 + c) % 9 + 1 for c in range(9)] for r in range(9)]
    rng = random.Random(seed)
    digits = list(range(1, 10))
    shuffled = digits[:]
    rng.shuffle(shuffled)
    mapping = {digits[i]: shuffled[i] for i in range(9)}
    base = [[mapping[n] for n in row] for row in base]
    # Permute rows only within each 3-row band, and bands as a whole.
    bands = [0, 1, 2]
    rng.shuffle(bands)
    rows = []
    for band in bands:
        inside = [0, 1, 2]
        rng.shuffle(inside)
        rows.extend([band * 3 + x for x in inside])
    stacks = [0, 1, 2]
    rng.shuffle(stacks)
    cols = []
    for stack in stacks:
        inside = [0, 1, 2]
        rng.shuffle(inside)
        cols.extend([stack * 3 + x for x in inside])
    return [[base[r][c] for c in cols] for r in rows]

