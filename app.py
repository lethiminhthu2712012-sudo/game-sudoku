def create_puzzle(level):
    solution = SOLUTIONS[level]
    puzzle = [row[:] for row in solution]
    blanks = LEVELS[level][2]
    cells = [(r, c) for r in range(9) for c in range(9)]
    random.Random(2026 + level).shuffle(cells)
    for r, c in cells[:blanks]:
        puzzle[r][c] = 0
    return puzzle

